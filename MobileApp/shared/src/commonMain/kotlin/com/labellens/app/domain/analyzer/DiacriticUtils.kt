package com.labellens.app.domain.analyzer

object DiacriticUtils {

    fun stripDiacritics(char: Char): Char = when (char) {
        'à', 'á', 'ả', 'ã', 'ạ', 'ă', 'ằ', 'ắ', 'ẳ', 'ẵ', 'ặ', 'â', 'ầ', 'ấ', 'ẩ', 'ẫ', 'ậ' -> 'a'
        'è', 'é', 'ẻ', 'ẽ', 'ẹ', 'ê', 'ề', 'ế', 'ể', 'ễ', 'ệ' -> 'e'
        'ì', 'í', 'ỉ', 'ĩ', 'ị' -> 'i'
        'ò', 'ó', 'ỏ', 'õ', 'ọ', 'ô', 'ồ', 'ố', 'ổ', 'ỗ', 'ộ', 'ơ', 'ờ', 'ớ', 'ở', 'ỡ', 'ợ' -> 'o'
        'ù', 'ú', 'ủ', 'ũ', 'ụ', 'ư', 'ừ', 'ứ', 'ử', 'ữ', 'ự' -> 'u'
        'ỳ', 'ý', 'ỷ', 'ỹ', 'ỵ' -> 'y'
        'đ' -> 'd'
        'À', 'Á', 'Ả', 'Ã', 'Ạ', 'Ă', 'Ằ', 'Ắ', 'Ẳ', 'Ẵ', 'Ặ', 'Â', 'Ầ', 'Ấ', 'Ẩ', 'Ẫ', 'Ậ' -> 'A'
        'È', 'É', 'Ẻ', 'Ẽ', 'Ẹ', 'Ê', 'Ề', 'Ế', 'Ể', 'Ễ', 'Ệ' -> 'E'
        'Ì', 'Í', 'Ỉ', 'Ĩ', 'Ị' -> 'I'
        'Ò', 'Ó', 'Ỏ', 'Õ', 'Ọ', 'Ô', 'Ồ', 'Ố', 'Ổ', 'Ỗ', 'Ộ', 'Ơ', 'Ờ', 'Ớ', 'Ở', 'Ỡ', 'Ợ' -> 'O'
        'Ù', 'Ú', 'Ủ', 'Ũ', 'Ụ', 'Ư', 'Ừ', 'Ứ', 'Ử', 'Ữ', 'Ự' -> 'U'
        'Ỳ', 'Ý', 'Ỷ', 'Ỹ', 'Ỵ' -> 'Y'
        'Đ' -> 'D'
        else -> char
    }

    fun stripDiacritics(text: String): String {
        val sb = StringBuilder(text.length)
        for (c in text) {
            if (c in '\u0300'..'\u036F') continue
            sb.append(stripDiacritics(c))
        }
        return sb.toString()
    }
}

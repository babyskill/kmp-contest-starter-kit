            // Check all aliases
            ingredient.aliases.any { alias ->
                // Clean punctuation for comparison
                val cleanAlias = alias.lowercase().trim()
                if (cleanAlias.length <= 2) {
                    // For short words, avoid false positives by checking word boundaries or exact containment
                    lower.contains(cleanAlias)
                } else {
                    lower.contains(cleanAlias)
                }
            }
        }
    }
